# 数据隐站 · Windows 打包脚本
#   powershell -ExecutionPolicy Bypass -File desktop\build_win.ps1
#
# 产物：
#   dist\Sanitized_Data\                     绿色版目录（可直接压缩分发）
#   dist_installer\Sanitized_Data_Setup_x64.exe   安装包（若装了 Inno Setup）
param([switch]$TestMode)
$ErrorActionPreference = 'Stop'
$Root = Split-Path $PSScriptRoot -Parent
Set-Location $Root

Write-Host "`n[1/6] 检查构建依赖" -ForegroundColor Cyan
$need = @()
python -c "import PyInstaller" 2>$null; if ($LASTEXITCODE -ne 0) { $need += 'pyinstaller' }
python -c "import webview"     2>$null; if ($LASTEXITCODE -ne 0) { $need += 'pywebview' }
# 条码/二维码识别引擎（P0 起必需，Apache-2.0，离线 wheel）
python -c "import zxingcpp"    2>$null; if ($LASTEXITCODE -ne 0) { $need += 'zxing-cpp' }
# 正射 TIF 中性化/大图（P0 起建议安装；缺失时自动降级为 Pillow + warning）
python -c "import rasterio, pyproj" 2>$null; if ($LASTEXITCODE -ne 0) {
    Write-Host "  ! 未安装 rasterio/pyproj：TIF 大图/位深/中性化会降级（见 docs/impl/tiff.md）" -ForegroundColor Yellow
}
if ($need.Count -gt 0) {
    Write-Host "  安装：$($need -join ', ')"
    python -m pip install --quiet --disable-pip-version-check @need
}
python -m PyInstaller --version

Write-Host "`n[1.5/7] 校验授权组件 keyring" -ForegroundColor Cyan
python deploy\verify_keyring.py --manifest app\server\yinzhan\licensing\public_keys.json
if ($LASTEXITCODE -ne 0) { throw '授权组件 keyring 校验失败：public_keys.json 未由 core 私钥签名或内容非法，拒绝打包' }
Write-Host "  ✓ keyring 签名有效"

Write-Host "`n[2/6] 拉取运行时安装包（WebView2 / VC++）" -ForegroundColor Cyan
& powershell -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'fetch_redist.ps1')

Write-Host "`n[3/6] PyInstaller 打包（onedir）" -ForegroundColor Cyan
$flagFile = Join-Path $Root 'app\server\yinzhan\_build_flags.py'
if ($TestMode) {
    # 测试构建：关闭收费门禁，朋友测试不被 3 份/天、20 页等限制卡住；
    # 正式构建不写此文件，保持 PAYWALL_ENABLED=True。
    [IO.File]::WriteAllText($flagFile,
        "# generated by build_win.ps1 -TestMode; removed after build`n" +
        "PAYWALL_ENABLED = False`nBUILD_CHANNEL = 'test'`n",
        (New-Object Text.UTF8Encoding($false)))
    Write-Host "  ! TEST MODE：收费门禁已关闭" -ForegroundColor Yellow
}
& python -m PyInstaller --clean --noconfirm (Join-Path $PSScriptRoot 'app.spec')
$buildExit = $LASTEXITCODE
if (Test-Path $flagFile) { Remove-Item $flagFile -Force -ErrorAction SilentlyContinue }
if ($buildExit -ne 0) { throw 'PyInstaller 失败' }

Write-Host "`n[3.5/7] 本地化：移除下载页/下载入口" -ForegroundColor Cyan
python (Join-Path $PSScriptRoot 'strip_local_web.py') --web-dir (Join-Path $Root 'dist\Sanitized_Data\_internal\web')
if ($LASTEXITCODE -ne 0) { throw '本地化 web 处理失败' }

Write-Host "`n[4/6] 补 VC++ 运行库 DLL（免装 VC++ 也能跑）" -ForegroundColor Cyan
$dist = Join-Path $Root 'dist\Sanitized_Data'
# PyInstaller 6 的 datas 会落到 _internal；客户端只认安装根目录/数据目录，
# 这里把默认商业服务地址再复制到根目录（部署后可用同目录文件覆盖）。
$commercialConfig = Join-Path $PSScriptRoot 'commercial.json'
if (Test-Path $commercialConfig) {
    Copy-Item $commercialConfig (Join-Path $dist 'commercial.json') -Force
    "  + commercial.json（默认商业服务地址）"
}
# DSH 检测插件（工具卡 + 右侧面板）随绿色版/安装包分发；用户用 dsh-plugin\install.ps1 安装。
$pluginSrc = Join-Path $Root 'integrations\dsh-plugin-sanitize-detect'
if (Test-Path $pluginSrc) {
    $pluginDst = Join-Path $dist 'dsh-plugin'
    Remove-Item $pluginDst -Recurse -Force -ErrorAction SilentlyContinue
    Copy-Item $pluginSrc $pluginDst -Recurse -Force
    "  + dsh-plugin\ (DSH 脱敏检测插件 $(Get-ChildItem $pluginDst -Recurse -File | Measure-Object).Count 个文件)"
}
foreach ($dll in @('msvcp140.dll', 'vcruntime140.dll', 'vcruntime140_1.dll')) {
    $src = Join-Path $env:SystemRoot "System32\$dll"
    if (Test-Path $src) {
        Copy-Item $src (Join-Path $dist $dll) -Force
        "  + $dll"
    } else {
        "  ! 未找到 $dll（系统里没有，安装时由 VC++ 安装包补齐）"
    }
}

Write-Host "`n[5/6] 自检：直接跑一次引擎" -ForegroundColor Cyan
$exe = Join-Path $dist 'Sanitized_Data.exe'
if (Test-Path $exe) {
    # 去掉可能从构建环境继承的「来自 Internet」标记；并用 .NET ProcessStartInfo
    # 的 UseShellExecute=$false 走 CreateProcess（Windows PowerShell 5.1 的
    # Start-Process 没有 -UseShellExecute 参数），避免 ShellExecute 触发
    # 「打开文件 - 安全警告」对话框把无人值守构建卡死（v1.1.0 构建时踩到过）。
    try { Unblock-File -Path $exe -ErrorAction SilentlyContinue } catch { }
    # 自检用独立端口 + 临时数据目录：既不碰用户真实数据，也不受本机已有旧实例影响
    $smokeData = Join-Path $Root 'build\_smoke_data'
    Remove-Item $smokeData -Recurse -Force -ErrorAction SilentlyContinue
    New-Item -ItemType Directory -Force -Path $smokeData | Out-Null
    $smokePort = 18760
    # Windows PowerShell 5.1 的 ProcessStartInfo.EnvironmentVariables 在部分环境为
    # null（Cannot index into a null array），这里改用进程级环境变量（子进程继承）。
    $oldPort = $env:YINZHAN_PORT
    $oldData = $env:YINZHAN_DATA_DIR
    $env:YINZHAN_PORT = "$smokePort"
    $env:YINZHAN_DATA_DIR = $smokeData
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $exe
    $psi.UseShellExecute = $false
    $psi.WindowStyle = [System.Diagnostics.ProcessWindowStyle]::Hidden
    $p = [System.Diagnostics.Process]::Start($psi)
    if ($null -eq $oldPort) { Remove-Item Env:YINZHAN_PORT -ErrorAction SilentlyContinue } else { $env:YINZHAN_PORT = $oldPort }
    if ($null -eq $oldData) { Remove-Item Env:YINZHAN_DATA_DIR -ErrorAction SilentlyContinue } else { $env:YINZHAN_DATA_DIR = $oldData }
    Start-Sleep -Seconds 10
    # 端口/版本都按本次实例校验，避免「自检命中了别的旧版本实例」造成假通过。
    $expectVersion = '1.1.2'
    try {
        $iv = Select-String -Path (Join-Path $PSScriptRoot 'installer.iss') -Pattern '#define MyAppVersion "([^"]+)"'
        if ($iv) { $expectVersion = $iv.Matches[0].Groups[1].Value }
    } catch { }
    $healthPort = $smokePort
    try {
        $runtime = Join-Path $smokeData 'runtime.json'
        $rt = Get-Content $runtime -Raw -ErrorAction Stop | ConvertFrom-Json
        if ($rt.pid -eq $p.Id -and $rt.port) { $healthPort = [int]$rt.port }
        else { Write-Host "  ! 警告：runtime.json pid=$($rt.pid) 与自检进程 $($p.Id) 不一致" -ForegroundColor Yellow }
    } catch { }
    try {
        $h = (Invoke-WebRequest "http://127.0.0.1:$healthPort/api/health" -UseBasicParsing -TimeoutSec 8).Content | ConvertFrom-Json
        "  ✓ 服务已启动  version=$($h.version)  OCR=$($h.engine.ocr)  解析器=$($h.engine.parsers -join ',')"
        # 打包关键自检：识别引擎与图像扫描器必须真的被收进包里
        "  扫描器=$($h.engine.scanners -join ',')  启用=$($h.engine.scan_enabled)"
        if ($h.version -ne $expectVersion) {
            Write-Host "  ! 警告：版本号不匹配（期望 $expectVersion，实际 $($h.version)）；可能命中了旧实例或包内版本未更新" -ForegroundColor Yellow
        }
        if (-not ($h.engine.scanners -contains 'barcode')) {
            Write-Host "  ! 警告：条形码扫描器未加载（检查 zxingcpp 是否被 collect_all 收进包）" -ForegroundColor Yellow
        }
        if ($h.engine.ocr -ne $true) {
            Write-Host "  ! 警告：OCR 未就绪（检查 rapidocr/onnxruntime 模型是否打进包）" -ForegroundColor Yellow
        }
        $ls = (Invoke-WebRequest "http://127.0.0.1:$healthPort/api/license/status" -UseBasicParsing -TimeoutSec 8).Content | ConvertFrom-Json
        if ($ls.keyring_ok -ne $true) {
            throw "打包自检失败：授权组件 keyring 未通过校验（keyring_ok=$($ls.keyring_ok)）"
        }
        "  ✓ 授权组件 keyring 已加载"
    } catch {
        "  ! 自检请求失败（可能窗口已打开但端口不同，检查 data\runtime.json）"
    }
    Get-Process -Id $p.Id -ErrorAction SilentlyContinue | Stop-Process -Force
}

Write-Host "`n[6/6] 打安装包（需要 Inno Setup 6）" -ForegroundColor Cyan
$iscc = @(
    "$env:ProgramFiles\Inno Setup 7\ISCC.exe",
    "${env:ProgramFiles(x86)}\Inno Setup 7\ISCC.exe",
    "$env:ProgramFiles\Inno Setup 6\ISCC.exe",
    "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe"
) | Where-Object { Test-Path $_ } | Select-Object -First 1

if ($iscc) {
    & $iscc (Join-Path $PSScriptRoot 'installer.iss')
    if ($LASTEXITCODE -eq 0) {
        "  ✓ 安装包：dist_installer\"
        Get-ChildItem (Join-Path $Root 'dist_installer') | Select-Object Name, @{n='MB';e={[math]::Round($_.Length/1MB,1)}}
    }
} else {
    "  ! 没找到 Inno Setup 6，跳过安装包。绿色版在 dist\Sanitized_Data\"
    "    下载：https://jrsoftware.org/isdl.php"
}

Write-Host "`n[7/7] 打绿色版压缩包" -ForegroundColor Cyan
$zip = Join-Path $Root "out\desktop\Sanitized_Data-$expectVersion-win64-portable.zip"
New-Item -ItemType Directory -Force -Path (Split-Path $zip) | Out-Null
Remove-Item $zip -Force -ErrorAction SilentlyContinue
Compress-Archive -Path (Join-Path $Root 'dist\Sanitized_Data') -DestinationPath $zip -CompressionLevel Optimal
"  ✓ $zip  $([math]::Round((Get-Item $zip).Length/1MB,1)) MB"

Write-Host "`n完成。" -ForegroundColor Green
